extension HexColor on Color {
  static Color fromHex(String hex) {
    hex = hex.replaceAll('#', '');
    if (hex.length == 6) {
      hex = "FF" + hex; // 8 char with opacity 100%
    }
    return Color(int.parse(hex, radix: 16));
  }
}
